"""Learner attempt schema representing recorded student practice evidence.

Generated by Track B intake; must explicitly distinguish baseline from retry.
"""

from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, model_validator
from .evidence import EvidenceRef


class AttemptType(str, Enum):
    BASELINE = "baseline"
    RETRY = "retry"


class ParticipantRef(BaseModel):
    """Reference to a human participant (learner or expert)."""

    participant_id: str = Field(..., description="Unique user or learner ID")
    name: str = Field(..., description="Display name of the participant")
    role: str = Field(default="learner", description="Role: learner, expert, mentor, reviewer")
    notes: Optional[str] = Field(None, description="Experience level, context, or cohort notes")


class LearnerAttempt(BaseModel):
    """Contract representing a learner's observable submission."""

    attempt_id: str = Field(..., description="Unique attempt identifier")
    task_id: str = Field(..., description="ID of the PracticeTask being attempted")
    learner: ParticipantRef = Field(..., description="Identity of the practicing learner")
    attempt_type: AttemptType = Field(
        ...,
        description="Whether this is the pre-training baseline or a post-feedback retry",
    )
    attempt_number: int = Field(
        default=1,
        ge=1,
        description="Sequential index of attempt for this task (1 = baseline, 2+ = retries)",
    )
    submitted_at: Optional[str] = Field(None, description="ISO timestamp of submission")
    evidence: EvidenceRef = Field(
        ...,
        description="Recorded multimodal evidence of the attempt (video, audio, text)",
    )

    @model_validator(mode="after")
    def validate_attempt_number_matches_type(self) -> "LearnerAttempt":
        if self.attempt_type == AttemptType.BASELINE:
            if self.attempt_number != 1:
                raise ValueError(
                    f"BASELINE attempt must have attempt_number == 1, got {self.attempt_number}"
                )
        elif self.attempt_type == AttemptType.RETRY:
            if self.attempt_number < 2:
                raise ValueError(
                    f"RETRY attempt must have attempt_number >= 2, got {self.attempt_number}"
                )
        return self
